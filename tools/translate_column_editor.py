def _apply(path: Path, pairs: list[tuple[str, str]], missing: list[str]) -> int:
    text = path.read_text(encoding="utf-8")
    done = 0
    for old, new in pairs:
        if old in text:
            text = text.replace(old, new)
            done += 1
        elif new not in text:
            missing.append(f"{path.relative_to(ROOT)}: {old[:90]!r}")
    path.write_text(text, encoding="utf-8")
    return done


def main() -> int:
    missing: list[str] = []
    qml_pairs = sorted(((f'"{en}"', f'"{de}"') for en, de in QML.items() if en != de), key=lambda p: -len(p[0]))
    total = 0
    used = set()
    for f in sorted((ROOT / "qml").glob("*.qml")):
        text = f.read_text(encoding="utf-8")
        for old, new in qml_pairs:
            if old in text:
                text = text.replace(old, new)
                used.add(old)
                total += 1
        f.write_text(text, encoding="utf-8")
    already = "".join(f.read_text(encoding="utf-8") for f in (ROOT / "qml").glob("*.qml"))
    missing += [f"qml: {o}" for o, n in qml_pairs if o not in used and n not in already]
    for rel, pairs in PY.items():
        total += _apply(ROOT / rel, pairs, missing)
    print(f"{total} Ersetzungen.")
    if missing:
        print(f"Nicht gefunden ({len(missing)}):")
        for m in missing:
            print("  " + m)
    sys.path.insert(0, str(ROOT.parent.parent))
    from p3d_pdfreader.column_editor import build_resources
    return build_resources.main()


